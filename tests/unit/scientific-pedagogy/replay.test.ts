import assert from "node:assert/strict";
import test from "node:test";
import { FSRS_4_5_DEFAULT_WEIGHTS, MIN_PREDICTIONS, fsrsRetrievability, fsrsUpdate, replaySchedulers, type ReviewEvent } from "../../../src/modules/scientific-pedagogy/replay.ts";

const DAY = 86_400_000;

function seeded(seed: number) {
  let state = seed >>> 0;
  return () => { state = (state * 1664525 + 1013904223) >>> 0; return state / 4294967296; };
}

/** Synthetic learner whose recall follows the FSRS power curve; reviews at varied delays. */
function syntheticLog(items: number, seed: number): ReviewEvent[] {
  const random = seeded(seed);
  const events: ReviewEvent[] = [];
  for (let item = 0; item < items; item += 1) {
    let stability = 0.5 + random() * 3;
    let at = Date.UTC(2026, 0, 1) + item * 3_600_000;
    events.push({ itemId: `i${item}`, at, success: true });
    for (let review = 0; review < 6; review += 1) {
      const elapsed = 1 + Math.floor(random() * 20);
      at += elapsed * DAY;
      const success = random() < fsrsRetrievability(elapsed, stability);
      events.push({ itemId: `i${item}`, at, success });
      stability = success ? stability * (1.8 + random()) : Math.max(0.3, stability * 0.4);
    }
  }
  return events;
}

test("FSRS curve: 90 % recall when elapsed time equals stability", () => {
  assert.ok(Math.abs(fsrsRetrievability(5, 5) - 0.9) < 1e-9);
  assert.equal(fsrsRetrievability(0, 5), 1);
  assert.ok(fsrsRetrievability(30, 5) < fsrsRetrievability(10, 5));
});

test("FSRS update: success after a delay raises stability, failure lowers it", () => {
  const start = { stability: FSRS_4_5_DEFAULT_WEIGHTS[2], difficulty: 5 };
  assert.ok(fsrsUpdate(start, 4, 3).stability > start.stability);
  assert.ok(fsrsUpdate(start, 4, 1).stability < start.stability);
  assert.ok(fsrsUpdate(start, 4, 1).difficulty > fsrsUpdate(start, 4, 3).difficulty);
});

test("replay is deterministic, ignores first reviews and same-session repeats", () => {
  const log: ReviewEvent[] = [
    { itemId: "a", at: 0, success: true },
    { itemId: "a", at: 3_600_000, success: true },
    { itemId: "a", at: 2 * DAY, success: false },
    { itemId: "b", at: 0, success: true },
  ];
  const report = replaySchedulers(log);
  assert.equal(report.items, 2);
  assert.equal(report.predictions, 1);
  assert.equal(report.enough, false);
  assert.deepEqual(replaySchedulers([...log].reverse()), report);
});

test("on a log generated by a memory process, the matching model scores better (evaluator sanity check)", () => {
  const report = replaySchedulers(syntheticLog(80, 42));
  assert.ok(report.enough && report.predictions >= MIN_PREDICTIONS);
  const [leitner, fsrs] = report.scores;
  assert.equal(leitner.scheduler, "CURRENT_V1");
  assert.ok(fsrs.logLoss < leitner.logLoss, `FSRS ${fsrs.logLoss} vs Leitner ${leitner.logLoss}`);
  assert.ok(fsrs.brier < leitner.brier);
  assert.equal(fsrs.observedRecall, leitner.observedRecall);
});

test("empty log gives an empty, explicit report", () => {
  const report = replaySchedulers([]);
  assert.equal(report.predictions, 0);
  assert.equal(report.enough, false);
  assert.ok(report.scores.every((score) => score.logLoss === 0));
});
